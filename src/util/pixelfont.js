// Calls fn(px, py) for every lit pixel of `text` (py = 0 at the top row).
export function eachPixel(text, fn) {
  let cx = 0;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] || G[' '];
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '1') fn(cx + x, y);
    cx += 6;
  }
  return cx - 1;
}

export function textWidth(text) { return text.length * 6 - 1; }
